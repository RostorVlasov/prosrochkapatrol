export function getFaqSlice(selection: Partial<Record<FaqCategoryKey, number>>): FaqItem[] {
  const result: FaqItem[] = []
  
  for (const [key, limit] of Object.entries(selection)) {
    const category = faqData[key as FaqCategoryKey]
    if (category) {
      result.push(...category.items.slice(0, limit))
    }
  }
  
  return result
}

